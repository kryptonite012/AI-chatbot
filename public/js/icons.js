/** Replaces <span data-icon="name"></span> placeholders in static HTML. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    el.outerHTML = icon(el.dataset.icon, el.className);
  }
}
